"""抽取招标第五章「工程量清单」→ 分部分项大类 + 占总造价比重(供技术卷"按占比定详略")。

让 LLM 通读工程量清单,归并成分部分项大类(路基/路面/桥涵/排水/交安…),逐类给出占总造价
比重(金额优先,无金额按工程量规模估)与主要清单项工程量。产出 JSON,由 boq_service 装进 TenderBOQ。
"""

from __future__ import annotations

_SYSTEM = (
    "你是公路/市政工程造价与工程量清单专家。任务:把招标「工程量清单」归并成分部分项大类,"
    "逐类估算其占总造价的比重,并列出主要清单项与工程量。铁律:工程量数值照抄清单原文、不得编造;"
    "比重优先按金额(招标控制价/分部分项合计)计算,清单无金额时按工程量规模与常规造价结构合理估算并注明依据。"
)

_INSTRUCTION = """通读下面的「工程量清单」,把分部分项归并成大类(如 路基工程、路面工程、桥涵工程、
排水与管网工程、交通安全与附属工程、绿化工程 等),输出**纯 JSON**(不要解释、不要 markdown 围栏):

{
  "total_amount_wan": 总造价(万元,招标控制价或清单合计;没有则 0),
  "note": "占比口径说明(如:按招标控制价分部合计 / 无金额按工程量规模估算)",
  "categories": [
    {
      "name": "分部分项大类名(如 路基工程)",
      "share_pct": 占总造价比重的数字(0-100,如 90),
      "key_quantities": "本类主要清单项与工程量(照抄清单数值与单位,如 路基填方12.6万m³、清表3.2万m²)",
      "basis": "金额 | 工程量估算"
    }
  ]
}

要点:
- categories 覆盖本工程量清单实际含有的**每个**分部分项大类;清单没有的类别不要出现。
- share_pct 各类相加约等于 100;占比要体现真实造价结构(如农村公路通常以路基+路面为主)。
- key_quantities 必须给出可写进施工方案的具体工程量(数值+单位),这是技术卷要引用的。
- 抽不到金额就按工程量规模估占比,并在 basis/note 注明"工程量估算"。

工程量清单正文:
---
{boq_text}
---
只输出 JSON。"""


def build_boq_prompt(boq_text: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": _SYSTEM},
        {"role": "user", "content": _INSTRUCTION.replace("{boq_text}", boq_text or "")},
    ]
